#!/usr/bin/env node
/**
 * Scans src/app/shared/components/<name>/*.component.ts and generates
 * src/app/features/component-library/component-registry.generated.ts —
 * the data source of the /component-library page.
 *
 * Runs automatically:
 *   - before `npm run build` (prebuild) and `npm start` (prestart), and
 *   - continuously while `npm start` is running (tools/dev.mjs watches
 *     shared/components and regenerates on any change),
 * so creating a new shared component folder makes it appear in the
 * Component Library with NO manual registry edits — even mid-serve.
 *
 * The card description comes from the JSDoc block above the component's
 * @Component decorator. Optional per-component preview settings (sample
 * inputs, example code, overlay flag) live in component-previews.ts.
 * Duplicate class names (e.g. a copied folder) are import-aliased, so
 * copies never break the build.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const componentsDir = join(projectRoot, 'src/app/shared/components');
const outFile = join(
  projectRoot,
  'src/app/features/component-library/component-registry.generated.ts',
);

// Last JSDoc block that appears before the @Component decorator.
function extractDescription(source) {
  const decoratorIndex = source.indexOf('@Component');
  const head = decoratorIndex === -1 ? source : source.slice(0, decoratorIndex);
  const blocks = [...head.matchAll(/\/\*\*([\s\S]*?)\*\//g)];
  if (!blocks.length) {
    return '';
  }
  return blocks[blocks.length - 1][1]
    .split('\n')
    .map((line) => line.replace(/^\s*\*? ?/, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** 'Test-selector copy' -> 'test-selector-copy' (safe URL id). */
function toId(folder) {
  return folder
    .trim()
    .replace(/[^A-Za-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase();
}

export function generate() {
  const entries = [];
  const usedIds = new Set();

  for (const folder of readdirSync(componentsDir).sort()) {
    const folderPath = join(componentsDir, folder);
    if (!statSync(folderPath).isDirectory()) {
      continue;
    }
    for (const file of readdirSync(folderPath).sort()) {
      if (!file.endsWith('.component.ts') || file.endsWith('.spec.ts')) {
        continue;
      }
      const source = readFileSync(join(folderPath, file), 'utf8');
      const classMatch = source.match(/export\s+class\s+([A-Za-z0-9_]+)/);
      if (!classMatch || !source.includes('@Component')) {
        continue;
      }
      let id = toId(folder);
      if (!id) {
        continue;
      }
      // Two folders (or two .component.ts in one folder) must not collide.
      while (usedIds.has(id)) {
        id = `${id}-${entries.length}`;
      }
      usedIds.add(id);
      entries.push({
        id,
        className: classMatch[1],
        // Unique local alias — duplicate class names (copied folders)
        // would otherwise produce clashing imports.
        alias: `Cmp${entries.length}`,
        importPath: `../../shared/components/${folder}/${file.replace(/\.ts$/, '')}`,
        description:
          extractDescription(source) || `Shared ${id.replace(/-/g, ' ')} component.`,
        // Components with required inputs cannot render live without
        // sample inputs (component-previews.ts) — rendering them anyway
        // throws NG0950 and breaks the page.
        requiredInputs:
          source.includes('input.required') || /@Input\(\s*\{[^}]*required\s*:\s*true/.test(source),
      });
    }
  }

  const banner = `/* eslint-disable */
// ============================================================
// AUTO-GENERATED by tools/generate-component-library.mjs
// Do NOT edit by hand — it is rewritten on every npm start/build
// and whenever shared/components changes while npm start runs.
// One entry per component folder under src/app/shared/components.
// Optional previews (sample inputs, example, overlay) belong in
// component-previews.ts, keyed by the entry id.
// ============================================================
import { Type } from '@angular/core';

`;

  const imports = entries
    .map((e) => `import { ${e.className} as ${e.alias} } from '${e.importPath}';`)
    .join('\n');

  const body = `

export interface GeneratedLibraryEntry {
  /** Slug of the folder name under shared/components — also the detail-page URL id. */
  id: string;
  component: Type<unknown>;
  /** JSDoc text extracted from the component source. */
  description: string;
  /** True when the component declares required inputs — a live preview
   *  then needs sampleInputs in component-previews.ts. */
  requiredInputs: boolean;
}

export const GENERATED_COMPONENT_LIBRARY: GeneratedLibraryEntry[] = [
${entries
  .map((e) => `  { id: '${e.id}', component: ${e.alias}, description: ${JSON.stringify(e.description)}, requiredInputs: ${e.requiredInputs} },`)
  .join('\n')}
];
`;

  const output = banner + imports + body;
  // Skip identical writes so the dev-server watch loop isn't retriggered.
  if (existsSync(outFile) && readFileSync(outFile, 'utf8') === output) {
    return { count: entries.length, changed: false };
  }
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, output);
  return { count: entries.length, changed: true };
}

const { count, changed } = generate();
console.log(
  `component-library: ${count} entries ${changed ? 'written to' : 'up to date in'} ` +
    outFile.replace(projectRoot + '/', ''),
);
